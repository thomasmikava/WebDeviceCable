// Development-time palette generation. No dependencies, seeds or preset accents.
// crypto.randomInt samples uniformly within the declared inclusive HSL ranges.
import { randomInt } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const cssPath = resolve(root, 'internal/bridge/web/theme.css');
const recordPath = resolve(root, 'scripts/theme-palette.json');
const ranges = {
  hue: [0, 359],
  canvas: { saturation: [8, 18], lightness: [6, 9] },
  surface: { saturation: [8, 16], lightness: [11, 14] },
  raised: { saturation: [7, 15], lightness: [16, 19] },
  hover: { saturation: [7, 14], lightness: [19, 22] },
  border: { saturation: [6, 13], lightness: [24, 28] },
  inputBorder: { saturation: [6, 13], lightness: [40, 46] },
  text: { saturation: [6, 16], lightness: [90, 95] },
  muted: { saturation: [5, 13], lightness: [66, 73] },
  accent: { saturation: [48, 76], lightness: [69, 78] },
  accentHover: { saturation: [48, 76], lightness: [79, 85] },
  soft: { saturation: [18, 30], lightness: [13, 17] },
  onAccent: { saturation: [8, 20], lightness: [6, 10] },
  success: { hue: [105, 165], saturation: [38, 62], lightness: [69, 79] },
  warning: { hue: [32, 55], saturation: [55, 80], lightness: [70, 80] },
  danger: { hue: [0, 18], saturation: [55, 78], lightness: [72, 81] },
};
const sample = range => randomInt(range[0], range[1] + 1);
function hsl(h, s, l) {
  s /= 100; l /= 100;
  const a = s * Math.min(l, 1 - l);
  const channel = n => { const k = (n + h / 30) % 12; return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))); };
  return '#' + [channel(0), channel(8), channel(4)].map(v => v.toString(16).padStart(2, '0')).join('');
}
function color(hue, range) { return hsl(hue, sample(range.saturation), sample(range.lightness)); }
function luminance(hex) {
  const rgb = hex.slice(1).match(/../g).map(c => parseInt(c, 16) / 255).map(c => c <= .04045 ? c / 12.92 : ((c + .055) / 1.055) ** 2.4);
  return .2126 * rgb[0] + .7152 * rgb[1] + .0722 * rgb[2];
}
function contrast(a, b) { const x = luminance(a), y = luminance(b); return (Math.max(x,y) + .05) / (Math.min(x,y) + .05); }
function checks(p) {
  const pairs = [];
  for (const foreground of ['text', 'muted', 'accent', 'success', 'warning', 'danger']) {
    for (const background of ['canvas', 'surface', 'surface-raised', 'surface-hover']) pairs.push([foreground, background, 4.5]);
  }
  for (const foreground of ['text', 'muted', 'accent']) pairs.push([foreground, 'accent-soft', 4.5]);
  for (const role of ['success', 'warning', 'danger']) pairs.push([role, `${role}-soft`, 4.5]);
  for (const background of ['accent', 'accent-hover']) pairs.push(['on-accent', background, 4.5]);
  for (const background of ['canvas', 'surface', 'surface-raised']) pairs.push(['input-border', background, 3]);
  return pairs.map(([fg,bg,minimum]) => ({ foreground:fg, background:bg, minimum, ratio:contrast(p[fg],p[bg]) }));
}
function makePalette() {
  const hue = sample(ranges.hue);
  const p = {};
  for (const [name, range] of Object.entries({canvas:ranges.canvas,surface:ranges.surface,'surface-raised':ranges.raised,'surface-hover':ranges.hover,border:ranges.border,'input-border':ranges.inputBorder,text:ranges.text,muted:ranges.muted,accent:ranges.accent,'accent-hover':ranges.accentHover,'accent-soft':ranges.soft,'on-accent':ranges.onAccent})) p[name] = color(hue,range);
  for (const role of ['success','warning','danger']) { const statusHue = sample(ranges[role].hue); p[role] = color(statusHue,ranges[role]); p[`${role}-soft`] = color(statusHue,ranges.soft); }
  p.scrim = '#00000099'; p.shadow = '#00000066';
  return { hue, palette:p };
}
function stylesheet(record) {
  return '/* Generated by scripts/generate-theme.mjs. Run npm run theme:generate to sample a new palette. */\n:root {\n  color-scheme: dark;\n' + Object.entries(record.palette).map(([name,value]) => `  --${name}: ${value};`).join('\n') + '\n}\n';
}
if (process.argv.includes('--check')) {
  const record = JSON.parse(await readFile(recordPath, 'utf8'));
  const results = checks(record.palette);
  if (results.some(c => c.ratio < c.minimum)) throw new Error('Stored palette does not meet contrast constraints.');
  if (await readFile(cssPath,'utf8') !== stylesheet(record)) throw new Error('Generated CSS differs from the recorded palette.');
  console.log(`Dark palette verified: ${results.length} contrast checks; accent ${record.palette.accent}, hue ${record.hue}°.`);
} else {
  // Reject only failed contrast constraints, never a hue or aesthetic preference.
  let result, results;
  for (let attempt = 0; attempt < 10000; attempt++) {
    result = makePalette(); results = checks(result.palette);
    if (results.every(c => c.ratio >= c.minimum)) break;
    result = undefined;
  }
  if (!result) throw new Error('Could not sample a readable palette within the ranges.');
  const record = { generator:'node:crypto.randomInt', ranges, ...result, contrast:results.map(c => ({...c,ratio:Number(c.ratio.toFixed(2))})) };
  await writeFile(cssPath,stylesheet(record)); await writeFile(recordPath,JSON.stringify(record,null,2)+'\n');
  console.log(`Generated dark palette: accent ${result.palette.accent}, hue ${result.hue}°; ${results.length} contrast constraints passed.`);
}
